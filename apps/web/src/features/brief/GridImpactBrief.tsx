import { AlertTriangle, CheckCircle2, Info, XCircle } from 'lucide-react'
import { Badge, cn } from '../../components/ui'
import { formatNumber, NO_VALUE } from '../../lib/format'
import type { BriefEvidence, BriefStatement, GridImpactBrief as Brief } from './brief'

const ICON = {
  ok: <CheckCircle2 aria-hidden className="mt-0.5 size-4 shrink-0 text-ok" />,
  info: <Info aria-hidden className="mt-0.5 size-4 shrink-0 text-info" />,
  warn: <AlertTriangle aria-hidden className="mt-0.5 size-4 shrink-0 text-warn" />,
  danger: <XCircle aria-hidden className="mt-0.5 size-4 shrink-0 text-danger" />,
} satisfies Record<BriefStatement['tone'], unknown>

const TONE_LABEL: Record<BriefStatement['tone'], string> = { ok: 'OK', info: 'Info', warn: 'Attention', danger: 'Critical' }

const SOURCE_LABEL: Record<BriefEvidence['source'], string> = {
  result: 'this run',
  baseline: 'baseline',
  mitigation: 'mitigation',
  scenario: 'scenario spec',
  network: 'network data',
}

function evidenceValue(e: BriefEvidence): string {
  if (e.value === null) return `${NO_VALUE} (not reported)`
  if (typeof e.value === 'number') return `${formatNumber(e.value, 6)}${e.unit ? ` ${e.unit}` : ''}`
  return `${String(e.value)}${e.unit ? ` ${e.unit}` : ''}`
}

/**
 * Renders a Grid Impact Brief: ordered statements, each with the exact fields and values it was
 * derived from (expand "Evidence"). Deterministic rules over stored data; no language model.
 */
export function GridImpactBrief({ brief, className, compact = false }: { brief: Brief; className?: string; compact?: boolean }) {
  return (
    <div className={cn('flex flex-col gap-2', className)} data-testid="grid-impact-brief">
      <p className="text-sm font-semibold text-fg" data-testid="brief-headline">
        {brief.headline}
      </p>
      <ol className="flex flex-col gap-1.5" aria-label="Brief statements">
        {brief.statements.map((s) => (
          <li key={s.id} className="flex gap-2 text-sm leading-snug" data-statement={s.id} data-tone={s.tone}>
            {ICON[s.tone]}
            <div className="min-w-0 flex-1">
              <span className="sr-only">{TONE_LABEL[s.tone]}: </span>
              <span className="text-fg">{s.text}</span>
              {s.evidence.length > 0 && (
                <details className="group mt-0.5 text-2xs text-fg-muted">
                  {/* -my-1 py-1: 24 px tap target (WCAG 2.5.8) without changing the line spacing. */}
                  <summary className="-my-1 cursor-pointer select-none py-1 text-accent underline-offset-2 hover:underline">
                    Evidence ({s.evidence.length})
                  </summary>
                  <dl className="mt-1 grid grid-cols-[auto_1fr] gap-x-2 gap-y-0.5 rounded border border-line bg-surface-2 p-1.5">
                    {s.evidence.map((e, i) => (
                      <div key={`${e.source}-${e.field}-${i}`} className="contents">
                        <dt className="font-mono text-fg-subtle">
                          <Badge className="mr-1 normal-case">{SOURCE_LABEL[e.source]}</Badge>
                          <span className="break-all">{e.field}</span>
                        </dt>
                        <dd className="tabular break-words text-fg">{evidenceValue(e)}</dd>
                      </div>
                    ))}
                  </dl>
                </details>
              )}
            </div>
          </li>
        ))}
      </ol>
      {!compact && (
        <ul className="mt-1 list-disc border-t border-line pt-1.5 pl-4 text-2xs text-fg-subtle" aria-label="Brief caveats">
          {brief.caveats.map((c) => (
            <li key={c}>{c}</li>
          ))}
          <li>Generated by deterministic rules over the stored data (no language model); the same inputs always give the same brief.</li>
        </ul>
      )}
    </div>
  )
}

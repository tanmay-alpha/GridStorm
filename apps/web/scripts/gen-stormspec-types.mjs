// Generates src/api/stormspec.gen.ts from the StormSpec JSON Schema (contract §3).
// Usage: npm run gen:stormspec
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const schemaPath = resolve(here, '../../../packages/stormspec/schema/stormspec-1.0.schema.json')
const outPath = resolve(here, '../src/api/stormspec.gen.ts')

const schema = JSON.parse(await readFile(schemaPath, 'utf8'))
const ts = await compile(schema, 'StormSpecScenario', {
  bannerComment:
    '/* eslint-disable */\n/**\n * GENERATED by scripts/gen-stormspec-types.mjs from\n * packages/stormspec/schema/stormspec-1.0.schema.json — do not edit by hand.\n */',
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: true, semi: false, printWidth: 110 },
})
await writeFile(outPath, ts)
console.log(`wrote ${outPath}`)
